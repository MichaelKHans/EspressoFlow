/**
 * Resolves a bean's price tier with safe fallback if not explicitly annotated
 */
export function resolveBeanPriceTier(item: CatalogCoffeeItem | CoffeeBeanProfile): PriceTier {
  if (item.priceTier) return item.priceTier;
  const price = item.approxPriceDkk || 0;
  if (price > 0) {
    if (price < 75) return 'budget';
    if (price <= 125) return 'standard';
    if (price <= 220) return 'premium';
    return 'ultra_rare';
  }
  // Heuristic based on SCA score or roaster
  const sca = ('scaScore' in item ? item.scaScore : (item as CoffeeBeanProfile).expertScore) || 0;
  if (sca >= 92) return 'ultra_rare';
  if (sca >= 88) return 'premium';
  const name = `${item.roaster || ''} ${item.name}`.toLowerCase();
  if (/lavazza|peter larsen|bki|merrild|löfbergs|zoégas|starbucks|segafredo|dallmayr|mövenpick/i.test(name)) {
    return 'budget';
  }
  return 'standard';
}

